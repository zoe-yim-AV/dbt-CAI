SELECT DISTINCT
S.SENDID	
,S.EVENTDATE
,DATE(S.EVENTDATE) AS SEND_DATE
,DATE_TRUNC('MONTH', DATE(S.EVENTDATE)) AS SEND_MONTH
,S.EVENTTYPE
,S.CLIENTID
,S.SUBSCRIBERKEY
,UPPER(S.EMAILADDRESS) AS EMAILADDRESS	
,CONCAT(S.SUBSCRIBERKEY,'-',UPPER(S.EMAILADDRESS)) AS SUBSCRIBERKEY_EMAIL
,J.SUBJECT
,J.EMAILNAME
,LU.CAMPAIGNID 
,C.CAMPAIGNCODE
,C."NAME" AS CAMPAIGN_NAME                                                     
,BM.BRAND                                                            
,BM.BRAND_LABEL       

// EMAIL_TYPE DERIVED COLUMN USING CONTAINS LOGIC ON EMAILNAME
,CASE 
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'PRODUCT')                  THEN 'Product'
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'BRAND')                    THEN 'Brand'
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'KAM')                      THEN 'KAM'
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'FIELD')                    THEN 'Field'
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'MARKETING WEEKLY EXPRESS') THEN 'Marketing Weekly Express'
    WHEN CONTAINS(UPPER(J.EMAILNAME), 'COMMERCIAL')               THEN 'Commercial'
    ELSE 'NA'
END AS EMAIL_TYPE

FROM CA_EPCA.MARKETING_CLOUD_HUB.MC_MAN_SENT S   
LEFT JOIN CA_EPCA.MARKETING_CLOUD_HUB.MC_SENDJOBS J
    ON S.SENDID = J.SENDID
    AND S.CLIENTID = J.CLIENTID

LEFT JOIN CAMPAIGN_LOOKUP LU
    ON S.SENDID = LU.SENDID
    
LEFT JOIN (SELECT DISTINCT CASE 
    WHEN CAMPAIGNID = '3313' THEN 'at_nada2026' 
    WHEN CAMPAIGNID = '3309' THEN 'EM-KAM-MAN-TOYOTA-INCENTIVE-2025'        // ADDED TO HANDLE ACTIVE DUPLICATION OF RECORDS
    // EX: SENDID: 9310085; SUBSCRIBERKEY: 0030Z00003CgnL5QAJ; SEND_DATE: 9/29/2025; CAMPAIGNID: 3309
    WHEN CAMPAIGNID = '3317' THEN 'rtl_nada2026'
    ELSE CAMPAIGNCODE END AS CAMPAIGNCODE, CAMPAIGNID, "NAME" FROM CA_EPCA.MARKETING_CLOUD_HUB.MC_CAMPAIGN_DATA
    WHERE CAMPAIGNCODE IS NOT NULL AND CAMPAIGNCODE != ''
    AND CAMPAIGNID IS NOT NULL AND CAMPAIGNID != ''
    ) C
    ON LU.CAMPAIGNID = C.CAMPAIGNID

// JOINED BRAND_MAPPING CTE ON CLIENTID = MID TO BRING IN BRAND AND BRAND_LABEL PER SEND
LEFT JOIN BRAND_MAPPING BM
    ON S.CLIENTID = BM.MID

WHERE DATE(S.EVENTDATE) >= DATEADD('MONTH', -12, DATE_TRUNC('MONTH', CURRENT_DATE))     ----WITHIN ROLLING 12 MONTHS


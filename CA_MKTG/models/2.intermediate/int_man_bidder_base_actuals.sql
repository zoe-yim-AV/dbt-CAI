SELECT 
DATE(CORE.ACT_OFFRNG_END_TS) AS SALE_DATE
,BA.REG_KEY
,CORE.VIN
,BIDDER_UID
,BIDDER_CONTACT_UID
,C.CONTACT__C AS CONTACT_GUID
,CONCAT(SALE_DATE,'-',C.CONTACT__C) AS SALE_DATE_GUID
,COUNT(BA.BID_AMT) AS BIDS

--,SUM(BA.HIGH_BID_FLG) AS BUYS
,CASE WHEN BA.HIGH_BID_FLG >= 1 THEN CORE.GROSS_TXN_FLG ELSE NULL END AS BUYS      

,CASE WHEN BA.HIGH_BID_FLG >= 1 THEN CORE.GROSS_TXN_FLG ELSE NULL END AS GROSS_TXNS
,CASE WHEN BA.HIGH_BID_FLG >= 1 THEN CORE.NET_TXN_FLG ELSE NULL END AS NET_TXNS

,CASE WHEN BA.HIGH_BID_FLG >= 1 THEN CORE.BUY_FEE_REVENUE ELSE NULL END AS BUY_FEES_REV
,CASE WHEN BA.HIGH_BID_FLG >= 1 THEN CORE.SELL_FEE_REVENUE ELSE NULL END AS SELL_FEES_REV

FROM DP.MAN_OVT.FACT_BUYING_ACTIVITY AS BA

LEFT JOIN CA_MKTG_INV_FIN_SOLUTIONS.DEV.CORE_OVT_TRANSACTIONS CORE         
    ON CORE.REG_KEY = BA.REG_KEY

LEFT JOIN CA_EPCA.SFDC_INV_MAN_HUB.PREFERENCES__C AS C
    ON BA.BIDDER_CONTACT_UID = C.REP_ID__C

WHERE DATE(CORE.ACT_OFFRNG_END_TS) >= DATEADD('MONTH', -12, DATE_TRUNC('MONTH', CURRENT_DATE))     ----WITHIN ROLLING 12 MONTHS
    --AND DATE(CORE.ACT_OFFRNG_END_TS) <= CURRENT_DATE ()
    AND CONTACT_GUID IN (SELECT DISTINCT SUBSCRIBERKEY FROM MAN_SENT_BASE)      // ENSURES ONLY INCLUDES THE GUIDS SENT

GROUP BY ALL


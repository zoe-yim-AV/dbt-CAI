,MAX(EVENTTYPE_OPEN) AS EVENTTYPE_OPEN
,MAX(EVENTTYPE_CLICK) AS EVENTTYPE_CLICK
,MAX(EVENTTYPE_BOUNCE) AS EVENTTYPE_BOUNCE
,MAX(EVENTTYPE_UNSUBSCRIBE) AS EVENTTYPE_UNSUBSCRIBE

// WORST-CASE BOT ROLLUP — IF ANY CLICK FOR THIS SUBSCRIBER/SEND WAS FLAGGED AS BOT, THE WHOLE SUBSCRIBER/SEND IS FLAGGED
// PRIORITY: SUSPECTED_BOT > INDETERMINATE > HUMAN > NO_CLICK
,MAX(CASE
    WHEN CLICK_CLASSIFICATION_RAW = 'SUSPECTED_BOT' THEN 3
    WHEN CLICK_CLASSIFICATION_RAW = 'INDETERMINATE' THEN 2
    WHEN CLICK_CLASSIFICATION_RAW = 'HUMAN' THEN 1
    ELSE 0 END) AS CLICK_CLASSIFICATION_PRIORITY

,CASE
    WHEN CLICK_CLASSIFICATION_PRIORITY = 3 THEN 'SUSPECTED_BOT'
    WHEN CLICK_CLASSIFICATION_PRIORITY = 2 THEN 'INDETERMINATE'
    WHEN CLICK_CLASSIFICATION_PRIORITY = 1 THEN 'HUMAN'
    ELSE 'NO_CLICK'
END AS CLICK_CLASSIFICATION_RAW

FROM MAN_COMBINED_ENGAGEMENT_METRICS



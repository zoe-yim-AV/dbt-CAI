,MAN_COMBINED_ENGAGEMENT_METRICS AS (
--CREATE OR REPLACE TEMPORARY TABLE MAN_COMBINED_ENGAGEMENT_METRICS AS (
--SELECT * FROM MAN_COMBINED_ENGAGEMENT_METRICS WHERE EVENT_DATE_UNSUBSCRIBE IS NOT NULL

SELECT
S.SEND_MONTH
,S.SENDID	
,S.EMAILNAME

,S.CAMPAIGNID 
,S.CAMPAIGNCODE 
,S.CAMPAIGN_NAME
,S.CLIENTID
,S.BRAND                                                             
,S.BRAND_LABEL                                                       
,S.EMAIL_TYPE                                                        

,S.EVENTDATE AS EVENT_TS_SENT	
,S.SEND_DATE 	
,S.SUBSCRIBERKEY	
,S.EMAILADDRESS	
,S.SUBSCRIBERKEY_EMAIL

,O.EVENTDATE AS EVENT_TS_OPEN
,DATE(O.EVENTDATE) AS EVENT_DATE_OPEN
,O.EVENTTYPE AS EVENTTYPE_OPEN              // PIXEL ONLY OPENS; "CLICK IMPLIES OPEN" INFERENCE REMOVED FOR ACCURACY (REMOVES BOT CLICK INFLATION)
--,CASE WHEN C.EVENTDATE IS NOT NULL THEN 'Open' ELSE O.EVENTTYPE END AS EVENTTYPE_OPEN   // OLD METHOD

,C.EVENTDATE AS EVENT_TS_CLICK
,DATE(C.EVENTDATE) AS EVENT_DATE_CLICK
,C.EVENTTYPE AS EVENTTYPE_CLICK

,C.URL                                      // ADDED FOR BOT DETECTION
,C.URLS_AT_SAME_TIMESTAMP                   // ADDED FOR BOT DETECTION

// RAW SIGNAL BEFORE HUMAN_OVERRIDE IS APPLIED DOWNSTREAM
,CASE
    WHEN C.URLS_AT_SAME_TIMESTAMP > 1
        AND O.EVENTDATE IS NULL THEN 'SUSPECTED_BOT'               // MULTIPLE URLS AT IDENTICAL TIMESTAMP AND NO OPEN — HIGH CONFIDENCE BOT
    WHEN C.URLS_AT_SAME_TIMESTAMP > 1
        AND DATEDIFF(SECOND, S.EVENTDATE, C.EVENTDATE) < 60 THEN 'SUSPECTED_BOT'    // MULTIPLE URLS WITHIN 60 SECONDS OF SEND — LIKELY SCANNER EVEN IF OPEN PIXEL FIRED
    WHEN C.EVENTDATE < O.EVENTDATE THEN 'SUSPECTED_BOT'            // CLICK BEFORE OPEN, PHYSICALLY IMPOSSIBLE FOR REAL HUMAN
    WHEN O.EVENTDATE IS NULL
        AND C.EVENTDATE IS NOT NULL
        AND C.URLS_AT_SAME_TIMESTAMP = 1 THEN 'INDETERMINATE'     // SINGLE URL CLICK WITH NO OPEN: COULD BE IMAGE BLOCKING (REAL HUMAN) OR SINGLE-LINK SCANNER; AMBIGUOUS
    WHEN C.EVENTDATE IS NULL THEN 'NO_CLICK'                      // NO CLICK ACTIVITY RECORDED
    ELSE 'HUMAN'
END AS CLICK_CLASSIFICATION_RAW

,U.EVENTDATE AS EVENT_TS_UNSUBSCRIBE
,DATE(U.EVENTDATE) AS EVENT_DATE_UNSUBSCRIBE
,U.EVENTTYPE AS EVENTTYPE_UNSUBSCRIBE

,B.EVENTDATE AS EVENT_TS_BOUNCE
,DATE(B.EVENTDATE) AS EVENT_DATE_BOUNCE
,B.EVENTTYPE AS EVENTTYPE_BOUNCE

FROM ref('int_man_sent_base') S

LEFT JOIN MAN_OPEN_BASE O  
    ON O.SENDID = S.SENDID
    AND O.SUBSCRIBERKEY_EMAIL = S.SUBSCRIBERKEY_EMAIL

LEFT JOIN MAN_CLICKS_BASE C
    ON C.SENDID = S.SENDID
    AND C.SUBSCRIBERKEY_EMAIL = S.SUBSCRIBERKEY_EMAIL

LEFT JOIN MAN_UNSUBSCRIBES_BASE U    
    ON U.SENDID = S.SENDID
    AND U.SUBSCRIBERKEY_EMAIL = S.SUBSCRIBERKEY_EMAIL

LEFT JOIN MAN_BOUNCES_BASE B
    ON B.SENDID = S.SENDID
    AND B.SUBSCRIBERKEY_EMAIL = S.SUBSCRIBERKEY_EMAIL
)


SELECT DISTINCT
SEND_DATE 
,EMAILNAME
,CAMPAIGNID 
,CAMPAIGNCODE 
,CAMPAIGN_NAME                                                       
,CLIENTID                                                            
,BRAND                                                                
,BRAND_LABEL                                                         
,EMAIL_TYPE

,SUBSCRIBERKEY
--,EMAILADDRESS

,EVENTTYPE_OPEN
,EVENTTYPE_CLICK
,EVENTTYPE_BOUNCE
,EVENTTYPE_UNSUBSCRIBE

,EM.CLICK_CLASSIFICATION_RAW

// FINAL BOT CLASSIFICATION WITH HUMAN_OVERRIDE FAILSAFE
// IF SUBSCRIBER HAD CONFIRMED CONVERSION ACTIVITY (BIDS OR BUYS) WITHIN THE 6-DAY POST-SEND WINDOW,
// RECLASSIFY AS HUMAN_OVERRIDE. REAL BUYERS SHOWING BOT-LIKE CLICK PATTERNS SHOULD NOT BE EXCLUDED
,CASE
    WHEN EM.CLICK_CLASSIFICATION_RAW = 'SUSPECTED_BOT'
        AND (SUM(ACT.BIDS) > 0 OR SUM(ACT.BUYS) > 0)
        THEN 'HUMAN_OVERRIDE'
    ELSE EM.CLICK_CLASSIFICATION_RAW
END AS CLICK_CLASSIFICATION

// DERIVED FLAG FOR DASHBOARD FILTERING
,CASE WHEN CLICK_CLASSIFICATION = 'SUSPECTED_BOT' THEN 'Y' ELSE 'N' END AS IS_BOT_CLICK

,SUM(BIDS) AS BIDS
,SUM(BUYS) AS BUYS
,SUM(GROSS_TXNS) AS GROSS_TXNS
,SUM(NET_TXNS) AS NET_TXNS
,SUM(BUY_FEES_REV) AS BUY_FEES_REV
,SUM(SELL_FEES_REV) AS SELL_FEES_REV

,CURRENT_DATE() AS BATCH_UPDATED_DT

FROM ref('int_agg_engagement_metrics') EM
LEFT JOIN ref('int_man_bidder_actuals') ACT
    ON ACT.CONTACT_GUID = EM.SUBSCRIBERKEY
    AND ACT.SALE_DATE > EM.SEND_DATE
    AND DATEDIFF(DAY,EM.SEND_DATE, ACT.SALE_DATE) <= 5     // WINDOWING WITHIN 6 DAYS AFTER SEND
    AND DATEDIFF(DAY,EM.SEND_DATE, ACT.SALE_DATE) >= 0 

GROUP BY ALL

);


END;

